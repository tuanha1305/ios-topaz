#!/usr/bin/env python3
"""Firmware tables of TopazModem.cpp for a phone's own modem partition (NON-HLOS, FAT16).

  fwtable.py MODEM_A.img NAME > iokit/Kernel/arm/TopazModemFw_NAME.h

The kernel reads the modem firmware straight from modem_a (read-only, sweet_ufs), so it has to
know where each file lies in that volume. This walks the FAT and writes, for every file, its
extents (offset in the partition, length) and, for the modem's own image (modem.mdt/.bNN, read
in one piece), offset, size and CRC32. Run it on a dump of the phone's partition
(`dd if=/dev/block/by-name/modem_a`): the modem's EFS must match the firmware, so the tables
are per phone model, not per SoC.
"""
import struct
import sys
import zlib

img_path, tag = sys.argv[1], sys.argv[2]
img = open(img_path, 'rb').read()

bps, spc, reserved, nfats, root_entries, total16, _media, spf = struct.unpack_from('<HBHBHHBH', img, 11)
total = total16 or struct.unpack_from('<I', img, 32)[0]
assert bps in (512, 1024, 2048, 4096) and spc and nfats, 'not a FAT volume'
fat_off = reserved * bps
root_off = fat_off + nfats * spf * bps
data_off = root_off + ((root_entries * 32 + bps - 1) // bps) * bps
cluster = spc * bps
fat = img[fat_off:fat_off + spf * bps]


def chain(first):
    c, out = first, []
    while 2 <= c < 0xFFF8:
        out.append(c)
        c = struct.unpack_from('<H', fat, c * 2)[0]
        assert len(out) < 1 << 20, 'FAT loop'
    return out


def extents(first, size):
    """[(offset in the partition, length)] of a file's clusters, runs merged."""
    runs, left = [], size
    for c in chain(first):
        off = data_off + (c - 2) * cluster
        n = min(cluster, left)
        if runs and runs[-1][0] + runs[-1][1] == off and runs[-1][1] % cluster == 0:
            runs[-1] = (runs[-1][0], runs[-1][1] + n)
        else:
            runs.append((off, n))
        left -= n
        if left <= 0:
            break
    assert left <= 0, 'chain shorter than the file'
    return runs


def entries(raw):
    lfn = []
    for i in range(0, len(raw), 32):
        e = raw[i:i + 32]
        if e[0] == 0:
            break
        if e[0] == 0xE5:
            lfn = []
            continue
        attr = e[11]
        if attr == 0x0F:
            part = e[1:11] + e[14:26] + e[28:32]
            lfn.insert(0, part.decode('utf-16le', 'ignore').split('\x00')[0].replace('￿', ''))
            continue
        if attr & 0x08:
            lfn = []
            continue
        short = e[0:8].decode('ascii', 'replace').rstrip()
        ext = e[8:11].decode('ascii', 'replace').rstrip()
        name = ''.join(lfn) if lfn else (short + ('.' + ext if ext else '')).lower()
        lfn = []
        if name in ('.', '..'):
            continue
        first = struct.unpack_from('<H', e, 26)[0]
        size = struct.unpack_from('<I', e, 28)[0]
        yield name, bool(attr & 0x10), first, size


def walk(raw, prefix, out):
    for name, is_dir, first, size in entries(raw):
        path = prefix + name
        if is_dir:
            data = b''.join(img[data_off + (c - 2) * cluster:data_off + (c - 1) * cluster] for c in chain(first))
            walk(data, path + '/', out)
        elif size:
            out.append((path, size, extents(first, size)))


files = []
walk(img[root_off:data_off], '', files)
files.sort()
assert len(files) < 0x10000

print('/* Generated by tools/fwtable.py from the %s modem_a dump (%d files); not to be edited. */' % (tag, len(files)))
ext_list, all_rows = [], []
for path, size, runs in files:
    all_rows.append((path, size, len(ext_list), len(runs)))
    ext_list.extend(runs)
print('static const struct fw_extent fw_ext_%s[] = {' % tag)
for off, n in ext_list:
    print('\t{ %#x, %#x },' % (off, n))
print('};')
print('static const struct fw_all_file fw_all_%s[] = {' % tag)
for path, size, ext, n in all_rows:
    print('\t{ "%s", %#x, %d, %d },' % (path, size, ext, n))
print('};')
print('static const struct fw_modem_file fw_files_%s[] = {' % tag)
for path, size, runs in files:
    base = path.rsplit('/', 1)[-1]
    if not (base == 'modem.mdt' or (base.startswith('modem.b') and base[7:].isdigit())):
        continue
    assert len(runs) == 1, '%s is fragmented: the modem image is read in one piece' % path
    off = runs[0][0]
    crc = zlib.crc32(img[off:off + size]) & 0xffffffff
    print('\t{ "%s", %#x, %#x, %#010x },' % (base, off, size, crc))
print('};')
